def coverage():
    summary = {}
    if set(CATALOG) != set(range(10)):
        raise ValueError('missing_category')
    for category, groups in CATALOG.items():
        subtypes = {}
        for subtype, short, descriptive in groups:
            if subtype in subtypes or len(short.split('|')) != 3 or len(descriptive.split('|')) != 7:
                raise ValueError('invalid_subtype_quota')
            subtypes[subtype] = dict(total=10, receipt_style=3)
        if len(subtypes) != 6:
            raise ValueError('invalid_category_quota')
        summary[category] = dict(total=60, receipt_style=18, subtypes=subtypes)
    return summary


def build_rows():
    coverage()
    rows = []
    for category, groups in CATALOG.items():
        for _, short, descriptive in groups:
            for name in short.split('|') + descriptive.split('|'):
                rows.append(dict(name=name, category=category, source='synthetic'))
    return validate_synthetic(rows)


def render():
    return ''.join(json.dumps(row, ensure_ascii=False) + '\n' for row in build_rows()).encode('utf-8')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='Verify the exported synthetic file without writing.')
    mode.add_argument('--force', action='store_true', help='Replace an existing synthetic export.')
    args = parser.parse_args()
    try:
        content = render()
        if args.check:
            if args.out.read_bytes() != content:
                raise ValueError('stale_synthetic_export')
        else:
            args.out.parent.mkdir(parents=True, exist_ok=True)
            with args.out.open('wb' if args.force else 'xb') as stream:
                stream.write(content)
        print(json.dumps(dict(total=len(build_rows()), categories=coverage()), ensure_ascii=True))
    except (ValueError, OSError):
        parser.exit(1, 'Synthetic generation failed; check quotas or output path.\n')


if __name__ == '__main__': main()
